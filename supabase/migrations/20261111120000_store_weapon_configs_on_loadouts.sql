-- A weapon config has one catalog weapon on the loadout itself. Its attachment
-- selections are a direct M2M relation on the loadout item in Directus.
ALTER TABLE public.loadouts
  ADD COLUMN weapon_id text REFERENCES public.weapons(id) ON DELETE RESTRICT;

CREATE INDEX idx_loadouts_weapon_id ON public.loadouts (weapon_id)
  WHERE weapon_id IS NOT NULL;

CREATE TABLE public.loadout_config_attachments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loadout_id text NOT NULL REFERENCES public.loadouts(id) ON DELETE CASCADE,
  attachment_id integer NOT NULL REFERENCES public.attachments(id) ON DELETE RESTRICT,
  UNIQUE (loadout_id, attachment_id)
);

CREATE INDEX idx_loadout_config_attachments_loadout
  ON public.loadout_config_attachments (loadout_id);
CREATE INDEX idx_loadout_config_attachments_attachment
  ON public.loadout_config_attachments (attachment_id);

ALTER TABLE public.loadout_config_attachments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public config attachments are viewable"
  ON public.loadout_config_attachments FOR SELECT
  USING (EXISTS (
    SELECT 1 FROM public.loadouts l
    WHERE l.id = loadout_id AND l.is_public = true
  ));

CREATE POLICY "Owners can view config attachments"
  ON public.loadout_config_attachments FOR SELECT
  USING (EXISTS (
    SELECT 1 FROM public.loadouts l
    WHERE l.id = loadout_id AND l.user_id = auth.uid()::text
  ));

CREATE POLICY "Owners can manage config attachments"
  ON public.loadout_config_attachments FOR ALL
  USING (EXISTS (
    SELECT 1 FROM public.loadouts l
    WHERE l.id = loadout_id AND l.user_id = auth.uid()::text
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM public.loadouts l
    WHERE l.id = loadout_id AND l.user_id = auth.uid()::text
  ));

-- Backfill existing configs without removing legacy slots yet: the deployed
-- edge function can keep reading them until its new version is published.
UPDATE public.loadouts l
SET weapon_id = lw.weapon_id
FROM public.loadout_weapons lw
WHERE l.id = lw.loadout_id AND l.content_type = 'weapon_config'
  AND lw.slot = 'primary';

INSERT INTO public.loadout_config_attachments (loadout_id, attachment_id)
SELECT l.id, lwa.attachment_id
FROM public.loadouts l
JOIN public.loadout_weapons lw ON lw.loadout_id = l.id AND lw.slot = 'primary'
JOIN public.loadout_weapon_attachments lwa ON lwa.loadout_weapon_id = lw.id
WHERE l.content_type = 'weapon_config'
ON CONFLICT (loadout_id, attachment_id) DO NOTHING;

-- Directus displays the relation on the loadout form; the junction collection
-- stays hidden in navigation, matching the other relation collections.
DO $$
BEGIN
  IF to_regclass('public.directus_collections') IS NOT NULL THEN
    INSERT INTO public.directus_collections (collection, hidden)
    VALUES ('loadout_config_attachments', true)
    ON CONFLICT (collection) DO UPDATE SET hidden = true;
  END IF;
  IF to_regclass('public.directus_fields') IS NOT NULL THEN
    INSERT INTO public.directus_fields
      (collection, field, special, interface, options, display, hidden, readonly, width, sort)
    SELECT 'loadouts', v.field, v.special, v.interface, v.options::json,
      v.display, false, false, 'full', v.sort
    FROM (VALUES
      ('weapon_id', 'm2o', 'select-dropdown-m2o', '{"template":"{{name}}"}', 'related-values', 2),
      ('config_attachments', 'm2m', 'list-m2m', '{"template":"{{attachment_id.name}}"}', NULL, 3)
    ) AS v(field, special, interface, options, display, sort)
    WHERE NOT EXISTS (SELECT 1 FROM public.directus_fields f
      WHERE f.collection = 'loadouts' AND f.field = v.field);
    INSERT INTO public.directus_fields
      (collection, field, special, interface, hidden, readonly, width)
    SELECT 'loadout_config_attachments', v.field, 'm2o',
      'select-dropdown-m2o', false, false, 'full'
    FROM (VALUES ('loadout_id'), ('attachment_id')) AS v(field)
    WHERE NOT EXISTS (SELECT 1 FROM public.directus_fields f
      WHERE f.collection = 'loadout_config_attachments' AND f.field = v.field);
  END IF;
  IF to_regclass('public.directus_relations') IS NOT NULL THEN
    INSERT INTO public.directus_relations
      (many_collection, many_field, one_collection, one_field, junction_field)
    SELECT v.many_collection, v.many_field, v.one_collection, v.one_field, v.junction_field
    FROM (VALUES
      ('loadouts', 'weapon_id', 'weapons', NULL, NULL),
      ('loadout_config_attachments', 'loadout_id', 'loadouts', 'config_attachments', 'attachment_id'),
      ('loadout_config_attachments', 'attachment_id', 'attachments', NULL, 'loadout_id')
    ) AS v(many_collection, many_field, one_collection, one_field, junction_field)
    WHERE NOT EXISTS (SELECT 1 FROM public.directus_relations r
      WHERE r.many_collection = v.many_collection AND r.many_field = v.many_field);
  END IF;
END $$;
